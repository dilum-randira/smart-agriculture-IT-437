"""Deterministic, SYNTHETIC hourly measurements for forecasting practice.

These numbers are generated by formulas and are NOT observations of Nai Miris,
IoT devices, or any real farm. Do not report their results as field evidence.
"""

import numpy as np
import pandas as pd


def make_synthetic_hourly_weather(hours: int = 24 * 120, seed: int = 42) -> pd.DataFrame:
    if hours < 72:
        raise ValueError("Use at least 72 hourly observations for the practice series")
    rng = np.random.default_rng(seed)
    t = np.arange(hours)
    daily = np.sin(2 * np.pi * (t % 24) / 24)
    slower = np.sin(2 * np.pi * t / (24 * 14))

    temperature = 29 + 4.5 * daily + 1.8 * slower + rng.normal(0, 0.7, hours)
    humidity = np.clip(73 - 12 * daily - 3 * slower + rng.normal(0, 2, hours), 0, 100)
    soil_moisture = np.clip(32 + 4 * np.sin(2 * np.pi * t / (24 * 7)) + rng.normal(0, 0.8, hours), 0, 100)
    return pd.DataFrame({
        "timestamp": pd.date_range("2026-01-01", periods=hours, freq="h", tz="UTC"),
        "air_temperature_c": temperature,
        "relative_humidity_pct": humidity,
        "synthetic_soil_moisture_pct": soil_moisture,
    })


if __name__ == "__main__":
    data = make_synthetic_hourly_weather()
    print("SYNTHETIC PRACTICE DATA — NOT FIELD MEASUREMENTS")
    print(data.head().to_string(index=False))
    print(f"Rows: {len(data)}, missing values: {int(data.isna().sum().sum())}")
